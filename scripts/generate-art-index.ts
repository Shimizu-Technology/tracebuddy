import { createHash } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const output = resolve(root, 'mobile/src/data/art.generated.ts')
const levels = ['simple', 'detailed'] as const
const categories = ['ocean', 'animals', 'dinosaurs', 'magic', 'go', 'nature', 'guam', 'fun', 'letters', 'shapes']
const lineDigest = createHash('sha256')

function entries(level: typeof levels[number]) {
  const directory = resolve(root, 'shared/art', level)
  const manifestPath = resolve(directory, 'manifest.json')
  if (!existsSync(manifestPath)) return []
  const manifest: unknown = JSON.parse(readFileSync(manifestPath, 'utf8'))
  const pictures = Array.isArray(manifest)
    ? manifest
    : (manifest as { pictures?: unknown } | null)?.pictures
  if (!Array.isArray(pictures)) {
    throw new Error(`${manifestPath} must contain an array of pictures or a pictures property.`)
  }

  const ids = new Set<string>()
  return pictures.map((picture: unknown) => {
    const { id, name, category } = (picture ?? {}) as Record<string, unknown>
    if (typeof id !== 'string' || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(id) ||
        typeof name !== 'string' || !name.trim() ||
        typeof category !== 'string' || !categories.includes(category) || ids.has(id)) {
      throw new Error(`Invalid or repeated picture in ${manifestPath}: ${JSON.stringify(picture)}`)
    }
    ids.add(id)
    const line = resolve(directory, id, 'line.svg')
    const svg = readFileSync(line, 'utf8').trim()
    if (!/<svg\b[^>]*\bviewBox=["']0 0 1000 1000["']/s.test(svg)) {
      throw new Error(`${level}/${id}/line.svg needs the 0 0 1000 1000 viewBox.`)
    }
    lineDigest.update(svg).update('\0')
    const color = resolve(directory, id, 'color.webp')
    if (!existsSync(color)) throw new Error(`Missing color image for ${level}/${id}.`)
    const colorPath = relative(dirname(output), color).replaceAll('\\', '/')
    const linePath = relative(dirname(output), line).replaceAll('\\', '/')
    return `    // eslint-disable-next-line @typescript-eslint/no-require-imports -- Metro needs literal asset requires.\n    { id: ${JSON.stringify(id)}, name: ${JSON.stringify(name)}, category: ${JSON.stringify(category)}, color: () => require(${JSON.stringify(colorPath)}), line: { kind: 'asset', moduleId: () => require(${JSON.stringify(linePath)}) } },`
  })
}

const generated = [
  '// Generated by npm run art:generate. Edit the manifests or artwork instead.',
  "import type { ArtLevel, GeneratedArt } from './catalog'",
  '',
  'export const generatedArt: Record<ArtLevel, readonly GeneratedArt[]> = {',
  ...levels.flatMap((level) => {
    const list = entries(level)
    return list.length === 0 ? [`  ${level}: [],`] : [`  ${level}: [`, ...list, '  ],']
  }),
  '}',
  `// Line art SHA-256: ${lineDigest.digest('hex')}`,
  '',
].join('\n')

if (process.argv.includes('--check')) {
  if (!existsSync(output) || readFileSync(output, 'utf8') !== generated) {
    throw new Error('The generated mobile art index is stale. Run npm run art:generate.')
  }
} else {
  writeFileSync(output, generated)
}
