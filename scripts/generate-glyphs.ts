import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import opentype from 'opentype.js'
import type { Font, Glyph, Path } from 'opentype.js'

type Variation = { wght: number; wdth: number }
// The published declarations predate these APIs in 2.0.
type GuideFont = Font & {
  variation?: { getTransform: (glyph: Glyph, coordinates: Variation) => Glyph }
  position: {
    getKerningTables: (script: string) => unknown[]
    getKerningValue: (tables: unknown[], left: number, right: number) => number
  }
}
type GuidePath = Path & { toPathData(options: { decimalPlaces: number; flipY: boolean }): string }

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const output = resolve(root, 'mobile/src/data/glyphs.generated.ts')
const alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789 .,!?'-&åÅñÑáÁéÉíÍóÓúÚüÜʼ’"

function glyphData(filename: string, variation?: Variation) {
  const bytes = readFileSync(resolve(root, 'scripts/fonts', filename))
  const font = opentype.parse(Uint8Array.from(bytes).buffer) as GuideFont
  const characters = Array.from(alphabet)
  const glyphs = characters.map((character) => {
    // Fredoka has no modifier apostrophe. Its right single quote has the matching shape.
    const glyph = font.charToGlyph(character === 'ʼ' && !font.hasChar(character) ? '’' : character)
    if (!glyph.index) throw new Error(`${filename} is missing ${JSON.stringify(character)}.`)
    // Reading path first initializes the point data that the variation processor uses.
    let path = glyph.path
    let advance = glyph.advanceWidth
    if (variation) {
      const transformed = font.variation?.getTransform(glyph, variation)
      if (!transformed) throw new Error(`${filename} does not support variable weights.`)
      path = transformed.path
      advance = transformed.advanceWidth
    }
    if (advance === undefined) throw new Error(`${filename} is missing an advance for ${character}.`)
    const { x1, y1, x2, y2 } = path.getBoundingBox()
    const d = (path as GuidePath).toPathData({ decimalPlaces: 1, flipY: false })
    if (!d && character !== ' ') throw new Error(`${filename} is missing the outline for ${character}.`)
    return { character, glyph, values: [d, advance, Math.floor(x1), Math.floor(y1), Math.ceil(x2), Math.ceil(y2)] }
  })
  const latinKerning = font.position.getKerningTables('latn')
  const pairs = glyphs.flatMap(({ character: left, glyph }) => {
    const row = glyphs.flatMap(({ character: right, glyph: next }) => {
      const value = latinKerning.length ? font.position.getKerningValue(latinKerning, glyph.index, next.index)
        : font.getKerningValue(glyph, next)
      return value ? [[right, value]] : []
    })
    return row.length ? [`      ${JSON.stringify(left)}: ${JSON.stringify(Object.fromEntries(row))},`] : []
  })
  const top = (character: string) => glyphs.find((glyph) => glyph.character === character)?.values[5]

  return [
    `    unitsPerEm: ${font.unitsPerEm}, capHeight: ${top('H')}, xHeight: ${top('x')},`,
    '    glyphs: {',
    ...glyphs.map(({ character, values }) => `      ${JSON.stringify(character)}: ${JSON.stringify(values)},`),
    '    },',
    ...(pairs.length ? ['    kerning: {', ...pairs, '    },'] : ['    kerning: {},']),
  ]
}

const generated = [
  '// Generated by npm run glyphs:generate. See scripts/fonts/README.md and ./font-licenses/.',
  'type Glyph = readonly [path: string, advance: number, xMin: number, yMin: number, xMax: number, yMax: number]',
  'type GuideFont = {',
  '  unitsPerEm: number',
  '  capHeight: number',
  '  xHeight: number',
  '  glyphs: Readonly<Partial<Record<string, Glyph>>>',
  '  kerning: Readonly<Partial<Record<string, Readonly<Partial<Record<string, number>>>>>>',
  '}',
  '',
  "export const guideFonts: Record<'bubble' | 'practice', GuideFont> = {",
  '  bubble: {',
  ...glyphData('Fredoka.ttf', { wght: 700, wdth: 100 }),
  '  },',
  '  practice: {',
  ...glyphData('Andika-Bold.ttf'),
  '  },',
  '}',
  '',
].join('\n')

if (process.argv.includes('--check')) {
  if (!existsSync(output) || readFileSync(output, 'utf8') !== generated) {
    throw new Error('The generated text glyphs are stale. Run npm run glyphs:generate.')
  }
} else {
  writeFileSync(output, generated)
}
